-- Tours 360: cotizaciones hechas desde /admin/tours/precios. Numeradas (COT-<año>-<número>), con el
-- cliente y todo el contenido en data (líneas, ITBIS sí/no, tasa, condiciones, datos bancarios sí/no).
-- Una cotización aceptada pasa a Contabilidad › Ingresos para emitir la factura con comprobante fiscal.
create table if not exists public.tour_quotes (
  id          uuid primary key default gen_random_uuid(),
  number      int generated by default as identity unique,
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now(),
  status      text not null default 'borrador' check (status in ('borrador', 'enviada', 'aceptada', 'rechazada', 'facturada')),
  client_name text not null default '',
  total_usd   numeric(12, 2) not null default 0,
  data        jsonb not null default '{}'::jsonb
);
create index if not exists tour_quotes_created_idx on public.tour_quotes (created_at desc);
alter table public.tour_quotes enable row level security;
drop policy if exists "admin_all" on public.tour_quotes;
create policy "admin_all" on public.tour_quotes for all to authenticated
  using (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'))
  with check (exists (select 1 from public.profiles where id = auth.uid() and role = 'admin'));
revoke all on public.tour_quotes from anon;
grant select, insert, update, delete on public.tour_quotes to authenticated, service_role;
